CREATE TABLE IF NOT EXISTS `user` (
    `user_id`             VARCHAR(64)   NOT NULL                COMMENT '用户ID',
    `email`               VARCHAR(255)  NULL                    COMMENT '邮箱',
    `password_hash`       VARCHAR(255)  NOT NULL                COMMENT '密码哈希',
    `nickname`            VARCHAR(255)  NOT NULL DEFAULT ''     COMMENT '昵称',
    `avatar_url`          VARCHAR(1024) NOT NULL DEFAULT ''     COMMENT '头像URL',
    `app_manager_level`    INT           NOT NULL DEFAULT 0      COMMENT '管理员级别',
    `global_recv_msg_opt` INT           NOT NULL DEFAULT 0      COMMENT '全局消息接收选项',
    `is_active`           TINYINT(1)    NOT NULL DEFAULT 1      COMMENT '是否激活',
    `area_code`           VARCHAR(16)   NOT NULL DEFAULT ''     COMMENT '手机区号',
    `phone_number`        VARCHAR(32)   NULL                    COMMENT '手机号',
    `account`             VARCHAR(64)   NULL                    COMMENT '账号',
    `gender`              INT           NOT NULL DEFAULT 0      COMMENT '性别：0未知 1男 2女',
    `birth_time`          DATETIME(3)   NULL                    COMMENT '生日',
    `level`               INT           NOT NULL DEFAULT 0      COMMENT '等级',
    `allow_vibration`     INT           NOT NULL DEFAULT 1      COMMENT '是否允许震动：1允许 2不允许',
    `allow_beep`          INT           NOT NULL DEFAULT 1      COMMENT '是否允许提示音：1允许 2不允许',
    `allow_add_friend`    INT           NOT NULL DEFAULT 1      COMMENT '是否允许加好友：1允许 2不允许',
    `register_type`       INT           NOT NULL DEFAULT 0      COMMENT '注册方式',
    `ex`                  VARCHAR(1024) NOT NULL DEFAULT ''     COMMENT '扩展字段',
    `protocol_version`    VARCHAR(32)   NOT NULL DEFAULT ''     COMMENT '已同意的协议版本',
    `protocol_agreed_at`  DATETIME(3)   NULL                    COMMENT '同意协议时间',
    `register_ip`         VARCHAR(64)   NOT NULL DEFAULT ''     COMMENT '注册 IP',
    `register_receipt`    VARCHAR(64)   NULL                    COMMENT '手机号注册核销回执',
    `create_time`         DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
    `updated_at`          DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间',
    PRIMARY KEY (`user_id`),
    UNIQUE INDEX `idx_email` (`email`),
    UNIQUE INDEX `uk_account` (`account`),
    UNIQUE INDEX `uk_phone` (`area_code`, `phone_number`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='用户基础信息表';

CREATE TABLE IF NOT EXISTS `auth_tokens` (
    `id`            VARCHAR(36)       NOT NULL COMMENT 'jti',
    `user_id`       VARCHAR(64)       NOT NULL COMMENT '用户ID',
    `platform_id`   INT               NOT NULL COMMENT '平台ID',
    `family_id`     VARCHAR(36)       NOT NULL COMMENT '刷新族ID，轮换/重放检测',
    `parent_jti`    VARCHAR(36)       NULL COMMENT '轮换前一个 refresh jti',
    `token_hash`    VARCHAR(64)       NULL COMMENT 'opaque 令牌 SHA-256；JWT 不存原文/摘要',
    `token_type`    VARCHAR(16)       NOT NULL COMMENT 'access|refresh',
    `expires_at`    DATETIME(3)       NOT NULL COMMENT '过期时间',
    `revoked_at`    DATETIME(3)       NULL COMMENT '撤销时间，NULL 表示有效',
    `revoke_reason` TINYINT UNSIGNED  NULL COMMENT '1 logout 2 kick 3 password 4 replay 5 ban',
    `created_at`    DATETIME(3)       NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
    PRIMARY KEY (`id`),
    INDEX `idx_user_platform` (`user_id`, `platform_id`),
    INDEX `idx_family` (`family_id`),
    INDEX `idx_token_hash` (`token_hash`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='认证令牌表';